func referencePRF(keyBytes []byte, roundIdx int, halfVal uint32) uint32 {
	msg := make([]byte, 5)
	msg[0] = byte(roundIdx)
	binary.BigEndian.PutUint32(msg[1:5], halfVal)
	mac := hmac.New(sha256.New, keyBytes)
	mac.Write(msg)
	return binary.BigEndian.Uint32(mac.Sum(nil)[:4])
}

func referenceFeistelEncrypt53(value uint64, keyBytes []byte) uint64 {
	left := (value >> RightBits) & leftMask
	right := value & rightMask
	for r := range FeistelRounds {
		if r%2 == 0 {
			left ^= uint64(referencePRF(keyBytes, r, uint32(right))) & leftMask
		} else {
			right ^= uint64(referencePRF(keyBytes, r, uint32(left))) & rightMask
		}
	}
	return (left << RightBits) | right
}

func TestFeistelMatchesReferenceImplementationAndPythonVectors(t *testing.T) {
	salt1 := "00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff"
	salt2 := "passphrase-longer-than-sha256-block-size-" + strings.Repeat("x", 64)

	// Golden Feistel vectors computed by reference Python b53 implementation.
	type feistelVec struct {
		plain  uint64
		wantS1 uint64
		wantS2 uint64
	}
	vectors := []feistelVec{
		{0, 1107075062941051, 7824595943983826},
		{1, 7976845591746947, 6164224278716882},
		{42, 7279543880053051, 4538220412827539},
		{(uint64(1) << 27) - 1, 5022653827680047, 1581405923215672},
		{uint64(1) << 27, 8588758884826748, 6857174416601736},
		{(uint64(1) << 52) + 12345, 2204969704736433, 4165915876270554},
		{(uint64(1) << 53) - 1, 3680838389222824, 2136886935822127},
	}

	k1, err := normalizeSalt(salt1)
	if err != nil {
		t.Fatalf("normalizeSalt(salt1) failed: %v", err)
	}
	k2, err := normalizeSalt(salt2)
	if err != nil {
		t.Fatalf("normalizeSalt(salt2) failed: %v", err)
	}

	for _, v := range vectors {
		got1 := feistelEncrypt53(v.plain, k1)
		if got1 != referenceFeistelEncrypt53(v.plain, k1) || got1 != v.wantS1 {
			t.Fatalf("salt1 Feistel(%d) = %d, want %d", v.plain, got1, v.wantS1)
		}
		if feistelDecrypt53(got1, k1) != v.plain {
			t.Fatalf("salt1 Feistel inverse(%d) mismatch", v.plain)
		}

		got2 := feistelEncrypt53(v.plain, k2)
		if got2 != referenceFeistelEncrypt53(v.plain, k2) || got2 != v.wantS2 {
			t.Fatalf("salt2 Feistel(%d) = %d, want %d", v.plain, got2, v.wantS2)
		}
		if feistelDecrypt53(got2, k2) != v.plain {
			t.Fatalf("salt2 Feistel inverse(%d) mismatch", v.plain)
		}
	}
}

func TestDeterministicGoldenVectorsAcrossAllLengths(t *testing.T) {
	const salt = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
	keyBytes, err := normalizeSalt(salt)
	if err != nil {
		t.Fatalf("normalizeSalt failed: %v", err)
	}

	for length := MinLen; length <= MaxLen; length++ {
		bits := make([]bool, length)
		var dataInt uint64
		for i := range length {
			if ((i*7 + 3) % 5) < 2 {
				bits[i] = true
				dataInt |= uint64(1) << i
			}
		}

		for _, nonce := range []uint64{0, nonceCounts[length] - 1} {
			plain53 := bases[length] + (nonce << length) + dataInt
			cipher53 := referenceFeistelEncrypt53(plain53, keyBytes)
			encoded := math.Ldexp(float64(cipher53), -MantissaBits)
			decoded, err := Decrypt(encoded, salt)
			if err != nil {
				t.Fatalf("Decrypt(len=%d, nonce=%d) failed: %v", length, nonce, err)
			}
			if !equalBools(decoded, bits) {
				t.Fatalf("Decrypt(len=%d, nonce=%d) mismatch", length, nonce)
			}
		}
	}
}

func TestFixedKnownPythonVectors(t *testing.T) {
	const salt = "00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff"
	keyBytes, err := normalizeSalt(salt)
	if err != nil {
		t.Fatalf("normalizeSalt failed: %v", err)
	}

	// Deterministic vector matching Python tests/test_vectors.py::test_fixed_known_vector.
	bits := []bool{true, false, true, true, false, false, true, false, true, true}
	var dataInt uint64
	for i, b := range bits {
		if b {
			dataInt |= uint64(1) << i
		}
	}
	plain53 := bases[len(bits)] + (uint64(12345) << len(bits)) + dataInt
	if plain53 != 59375165261 {
		t.Fatalf("plain53 = %d, want 59375165261", plain53)
	}
	cipher53 := feistelEncrypt53(plain53, keyBytes)
	if cipher53 != 2612494001650278 {
		t.Fatalf("cipher53 = %d, want 2612494001650278", cipher53)
	}
	encoded := math.Ldexp(float64(cipher53), -MantissaBits)
	wantHexVal, err := strconv.ParseFloat("0x1.2901951e474ccp-2", 64)
	if err != nil {
		t.Fatal(err)
	}
	if encoded != wantHexVal {
		t.Fatalf("encoded = %v, want %v", encoded, wantHexVal)
	}

	// Real ciphertexts generated by Python b53 across various lengths.
	pythonCiphertexts := []struct {
		floatStr string
		hexFloat string
		wantBits string
	}{
		{"0.29004509923272503", "0x1.2901951e474ccp-2", "1011001011"},
		{"0.13142950856601443", "0x1.0d2aea0829bf0p-3", "1"},
		{"0.6144246327891283", "0x1.3a95dd8f5f4a8p-1", "0"},
		{"0.74165970986907", "0x1.7bbad24d4c08cp-1", "1011001011"},
		{"0.8027294113813265", "0x1.9aff5972d71afp-1", "1010101010101010101010101"},
		{"0.870623548918328", "0x1.bdc25eab769e2p-1", "11001110011100111001110011100111001110011100111001"},
	}

	cipher, err := NewCipher(salt)
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range pythonCiphertexts {
		vDec, err := strconv.ParseFloat(tc.floatStr, 64)
		if err != nil {
			t.Fatal(err)
		}
		vHex, err := strconv.ParseFloat(tc.hexFloat, 64)
		if err != nil {
			t.Fatal(err)
		}
		if vDec != vHex {
			t.Fatalf("decimal %s != hex %s", tc.floatStr, tc.hexFloat)
		}
		got, err := cipher.DecryptString(vDec)
		if err != nil {
			t.Fatalf("DecryptString(%s) failed: %v", tc.floatStr, err)
		}
		if got != tc.wantBits {
			t.Fatalf("DecryptString(%s) = %q, want %q", tc.floatStr, got, tc.wantBits)
		}
	}
}
